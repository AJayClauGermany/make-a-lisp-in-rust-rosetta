//! `cargo xtask report` and `cargo xtask compare`: render recorded runs.
//!
//! The results page is generated in full from the newest run under `runs/`
//! and the implementation registry, so it always shows every registered
//! implementation, measured or not, and the numbers behind it are the
//! committed ones.

use std::fmt::Write as _;
use std::fs;

use mal_traits::{Component, Implementation};

use crate::run::{Benchmark, Run, Throughput};
use crate::{Result, workspace_root};

/// Where the generated page lives, relative to the workspace root.
pub const RESULTS_PAGE: &str = "docs/src/results.md";

const REPOSITORY: &str = env!("CARGO_PKG_REPOSITORY");

/// `report [--check]`.
pub fn run(args: &[String]) -> Result<()> {
    let check = match args {
        [] => false,
        [flag] if flag == "--check" => true,
        other => return Err(format!("unknown arguments for report: {}", other.join(" ")).into()),
    };
    let root = workspace_root();
    let runs = Run::load_all(&root)?;
    let rendered = render(&runs, &mal::registry::all());
    let path = root.join(RESULTS_PAGE);
    let current = fs::read_to_string(&path).unwrap_or_default();
    if current == rendered {
        eprintln!("{RESULTS_PAGE} is up to date");
        return Ok(());
    }
    if check {
        return Err(format!(
            "{RESULTS_PAGE} is out of date; run `cargo xtask report` and commit the result"
        )
        .into());
    }
    fs::write(&path, rendered)?;
    eprintln!("wrote {RESULTS_PAGE}");
    Ok(())
}

/// `compare <RUN> <RUN>`: the benchmarks both runs have, side by side.
pub fn compare(args: &[String]) -> Result<()> {
    let [from, to] = args else {
        return Err("compare takes exactly two run ids".into());
    };
    let runs = Run::load_all(&workspace_root())?;
    let find = |id: &str| {
        runs.iter()
            .find(|r| r.id == id)
            .ok_or_else(|| format!("no run `{id}` under runs/"))
    };
    let (from, to) = (find(from)?, find(to)?);
    let mut out = String::new();
    let _ = writeln!(
        out,
        "{:<40} {:>12} {:>12} {:>9}",
        "benchmark",
        from.id.get(..15).unwrap_or(&from.id),
        to.id.get(..15).unwrap_or(&to.id),
        "change"
    );
    let mut shared = 0;
    for b in &to.benchmarks {
        if let Some(a) = from.benchmark(&b.id) {
            shared += 1;
            let _ = writeln!(
                out,
                "{:<40} {:>12} {:>12} {:>9}",
                b.id,
                duration(a.mean_ns),
                duration(b.mean_ns),
                delta(b.mean_ns, a.mean_ns)
            );
        }
    }
    if shared == 0 {
        return Err("the two runs have no benchmarks in common".into());
    }
    print!("{out}");
    Ok(())
}

/// Render the results page from `runs` (newest first) and the registry.
pub fn render(runs: &[Run], registry: &[&Implementation]) -> String {
    let mut out = String::new();
    let latest = runs.first();
    let previous = runs.get(1);

    out.push_str("# Results\n\n");
    out.push_str(
        "<!-- Generated by `cargo xtask report` from the newest run under `runs/` and\n\
         the implementation registry. Do not edit by hand: CI checks that this page\n\
         matches the generator. To change the layout, edit `xtask/src/report.rs`. -->\n\n",
    );

    match latest {
        Some(run) => render_run_header(&mut out, run, previous),
        None => out.push_str(
            "No benchmark runs have been recorded yet. `cargo xtask bench` records one\n\
             under `runs/` and regenerates this page. The sections below list the\n\
             registered implementations; measured columns appear once a run exists.\n\n",
        ),
    }

    for component in Component::ALL {
        render_component(&mut out, component, registry, latest, previous);
    }

    render_runs_index(&mut out, runs);
    out
}

fn render_run_header(out: &mut String, run: &Run, previous: Option<&Run>) {
    let _ = writeln!(
        out,
        "Newest run: [`{}`]({REPOSITORY}/blob/main/runs/{}/results.json), recorded {}.\n",
        run.id,
        run.id,
        run.recorded_at.replace('T', " ").replace('Z', " UTC")
    );
    out.push_str("| | |\n|---|---|\n");
    let mut host = format!(
        "`{}`, {} {}, {} logical CPUs",
        run.host.name, run.host.os, run.host.arch, run.host.cpus
    );
    if let Some(model) = &run.host.cpu_model {
        let _ = write!(host, ", {model}");
    }
    let _ = writeln!(out, "| host | {host} |");
    let _ = writeln!(out, "| toolchain | `{}` |", run.toolchain.rustc);
    let commit = match &run.commit {
        Some(c) => format!(
            "[`{c}`]({REPOSITORY}/commit/{c}){}",
            if run.dirty {
                " with uncommitted changes"
            } else {
                ""
            }
        ),
        None => "not a git checkout".to_owned(),
    };
    let _ = writeln!(out, "| commit | {commit} |");
    let _ = writeln!(out, "| command | `{}` |", run.command.join(" "));
    match previous {
        Some(p) => {
            let _ = writeln!(
                out,
                "| compared against | [`{}`]({REPOSITORY}/blob/main/runs/{}/results.json) on `{}` |",
                p.id, p.id, p.host.name
            );
        }
        None => out.push_str("| compared against | no earlier run |\n"),
    }
    out.push('\n');
    out.push_str(
        "Times are Criterion's point estimate of the mean per iteration, with the\n\
         standard deviation; throughput divides the declared input size by the mean.\n\
         The *vs previous* column is the change in mean against the previous run, which\n\
         is only meaningful when both runs come from the same host. Workloads are the\n\
         fixed inputs in `mal_bench::corpus`, shared by every implementation of a\n\
         component.\n\n",
    );
}

fn render_component(
    out: &mut String,
    component: Component,
    registry: &[&Implementation],
    latest: Option<&Run>,
    previous: Option<&Run>,
) {
    let _ = writeln!(out, "## {}\n", component.title());
    let registered: Vec<&Implementation> = registry
        .iter()
        .copied()
        .filter(|imp| imp.component == component)
        .collect();
    let measured: Vec<&Benchmark> = latest
        .map(|run| {
            run.benchmarks
                .iter()
                .filter(|b| b.component == component.slug())
                .collect()
        })
        .unwrap_or_default();

    if registered.is_empty() && measured.is_empty() {
        out.push_str("No implementations registered yet.\n\n");
        return;
    }

    for imp in &registered {
        let crates = if imp.is_baseline() {
            "no third-party crates".to_owned()
        } else {
            imp.crates
                .iter()
                .map(|c| format!("[{} {}]({})", c.name, c.version, c.url))
                .collect::<Vec<_>>()
                .join(", ")
        };
        let _ = writeln!(
            out,
            "- **{}**: reaches `{}`; {crates}. {}",
            imp.name, imp.highest_step, imp.notes
        );
    }
    out.push('\n');

    if latest.is_none() {
        return;
    }

    let with_delta = previous.is_some();
    out.push_str("| implementation | workload | mean | std dev | throughput |");
    if with_delta {
        out.push_str(" vs previous |");
    }
    out.push_str("\n|---|---|---:|---:|---:|");
    if with_delta {
        out.push_str("---:|");
    }
    out.push('\n');

    let mut names: Vec<&str> = registered.iter().map(|imp| imp.name).collect();
    for b in &measured {
        if !names.contains(&b.implementation.as_str()) {
            names.push(&b.implementation);
        }
    }
    for name in names {
        let rows: Vec<&&Benchmark> = measured
            .iter()
            .filter(|b| b.implementation == name)
            .collect();
        let unregistered = !registered.iter().any(|imp| imp.name == name);
        let label = if unregistered {
            format!("{name} (no longer registered)")
        } else {
            name.to_owned()
        };
        if rows.is_empty() {
            let _ = write!(out, "| {label} | *not measured in this run* | | | |");
            if with_delta {
                out.push_str(" |");
            }
            out.push('\n');
            continue;
        }
        for b in rows {
            let _ = write!(
                out,
                "| {label} | `{}` | {} | {} | {} |",
                b.workload,
                duration(b.mean_ns),
                duration(b.std_dev_ns),
                throughput(b)
            );
            if let Some(p) = previous {
                let cell = p
                    .benchmark(&b.id)
                    .map_or_else(|| "new".to_owned(), |old| delta(b.mean_ns, old.mean_ns));
                let _ = write!(out, " {cell} |");
            }
            out.push('\n');
        }
    }
    out.push('\n');
}

fn render_runs_index(out: &mut String, runs: &[Run]) {
    out.push_str("## Recorded runs\n\n");
    if runs.is_empty() {
        out.push_str("None yet.\n");
        return;
    }
    out.push_str(
        "Newest first. Each row links to the raw `results.json`; `cargo xtask compare <a> <b>`\n\
         prints the benchmarks two runs share.\n\n",
    );
    out.push_str("| run | recorded (UTC) | host | toolchain | commit | benchmarks |\n|---|---|---|---|---|---:|\n");
    for run in runs {
        let commit = run
            .commit
            .as_deref()
            .map_or_else(|| "-".to_owned(), |c| format!("`{c}`"));
        let _ = writeln!(
            out,
            "| [`{}`]({REPOSITORY}/blob/main/runs/{}/results.json) | {} | `{}` | `{}` | {} | {} |",
            run.id,
            run.id,
            run.recorded_at.replace('T', " ").trim_end_matches('Z'),
            run.host.name,
            run.toolchain.rustc,
            commit,
            run.benchmarks.len()
        );
    }
}

/// Nanoseconds as a human-readable duration with three significant digits.
pub fn duration(ns: f64) -> String {
    let (value, unit) = if ns < 1_000.0 {
        (ns, "ns")
    } else if ns < 1_000_000.0 {
        (ns / 1_000.0, "µs")
    } else if ns < 1_000_000_000.0 {
        (ns / 1_000_000.0, "ms")
    } else {
        (ns / 1_000_000_000.0, "s")
    };
    format!("{} {unit}", significant(value))
}

// Input sizes are far below 2^52 bytes, so the u64 -> f64 cast is exact.
#[allow(clippy::cast_precision_loss)]
fn throughput(b: &Benchmark) -> String {
    if b.mean_ns <= 0.0 {
        return "-".to_owned();
    }
    let per_second = |amount: u64| amount as f64 / (b.mean_ns / 1_000_000_000.0);
    match b.throughput {
        None => "-".to_owned(),
        Some(Throughput::Bytes(n)) => {
            let rate = per_second(n);
            let (value, unit) = if rate < 1024.0 {
                (rate, "B/s")
            } else if rate < 1024.0 * 1024.0 {
                (rate / 1024.0, "KiB/s")
            } else if rate < 1024.0 * 1024.0 * 1024.0 {
                (rate / (1024.0 * 1024.0), "MiB/s")
            } else {
                (rate / (1024.0 * 1024.0 * 1024.0), "GiB/s")
            };
            format!("{} {unit}", significant(value))
        }
        Some(Throughput::Elements(n)) => {
            let rate = per_second(n);
            let (value, unit) = if rate < 1_000.0 {
                (rate, "elem/s")
            } else if rate < 1_000_000.0 {
                (rate / 1_000.0, "Kelem/s")
            } else {
                (rate / 1_000_000.0, "Melem/s")
            };
            format!("{} {unit}", significant(value))
        }
    }
}

/// Relative change of `new` against `old`, as a signed percentage.
pub fn delta(new: f64, old: f64) -> String {
    if old <= 0.0 {
        return "-".to_owned();
    }
    let percent = (new - old) / old * 100.0;
    format!("{percent:+.1}%")
}

/// Three significant digits, without scientific notation.
fn significant(value: f64) -> String {
    if value >= 100.0 {
        format!("{value:.0}")
    } else if value >= 10.0 {
        format!("{value:.1}")
    } else {
        format!("{value:.2}")
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::run::{Host, Toolchain};

    fn run(id: &str, mean: f64) -> Run {
        Run {
            schema: crate::run::SCHEMA,
            id: id.into(),
            recorded_at: "2026-01-02T03:04:05Z".into(),
            host: Host {
                name: "box".into(),
                os: "linux".into(),
                arch: "x86_64".into(),
                cpus: 8,
                cpu_model: Some("Example CPU".into()),
            },
            toolchain: Toolchain {
                rustc: "rustc 1.85.0".into(),
            },
            commit: Some("abcdef123456".into()),
            dirty: false,
            command: vec!["cargo".into(), "bench".into()],
            benchmarks: vec![Benchmark {
                id: "eval/echo/rep/atom".into(),
                component: "eval".into(),
                implementation: "echo".into(),
                workload: "rep/atom".into(),
                mean_ns: mean,
                median_ns: mean,
                std_dev_ns: 1.5,
                throughput: Some(Throughput::Bytes(2)),
            }],
        }
    }

    #[test]
    fn formats_units() {
        assert_eq!(duration(12.345), "12.3 ns");
        assert_eq!(duration(1_234.0), "1.23 µs");
        assert_eq!(duration(123_456_789.0), "123 ms");
        assert_eq!(duration(2.5e9), "2.50 s");
        assert_eq!(delta(110.0, 100.0), "+10.0%");
        assert_eq!(delta(90.0, 100.0), "-10.0%");
        assert_eq!(delta(1.0, 0.0), "-");
    }

    #[test]
    fn renders_without_runs() {
        let page = render(&[], &mal::registry::all());
        assert!(page.starts_with("# Results\n"));
        assert!(page.contains("No benchmark runs have been recorded yet."));
        assert!(page.contains("## Evaluator"));
        assert!(page.contains("- **echo**: reaches `step0_repl`; no third-party crates."));
        assert!(page.contains("## Reader\n\nNo implementations registered yet."));
        assert!(page.contains("## Recorded runs\n\nNone yet.\n"));
    }

    #[test]
    fn renders_latest_run_with_delta_and_unmeasured_rows() {
        let runs = [
            run("20260102-030405-box", 50.0),
            run("20260101-000000-box", 40.0),
        ];
        let page = render(&runs, &mal::registry::all());
        assert!(page.contains("Newest run: [`20260102-030405-box`]"));
        assert!(page.contains("| compared against | [`20260101-000000-box`]"));
        assert!(page.contains("| echo | `rep/atom` | 50.0 ns | 1.50 ns | 38.1 MiB/s | +25.0% |"));
        // The std line editor is registered but has no time benchmark.
        assert!(page.contains("| std | *not measured in this run* | | | | |"));
        assert!(page.contains("| [`20260101-000000-box`]"));
    }

    #[test]
    fn single_run_has_no_delta_column() {
        let page = render(&[run("20260102-030405-box", 50.0)], &mal::registry::all());
        assert!(page.contains("| compared against | no earlier run |"));
        assert!(page.contains("| implementation | workload | mean | std dev | throughput |\n"));
        assert!(!page.contains("vs previous |"));
    }
}
